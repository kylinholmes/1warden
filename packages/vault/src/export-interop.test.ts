import { describe, expect, it } from 'vitest';
import { readFileSync, realpathSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname } from 'node:path';
import { createVaultExport } from './export';
import { parseImport } from './import-dispatch';
import { emptyLogin, type VaultItem } from './model';

/** Load the pinned official CLI in memory, replacing only its application entrypoint.
 * No credentials, CLI profile, network or external account is used. The algorithms,
 * serializer and importers below are the unmodified Bitwarden implementation.
 */
function officialCode() {
  const file = realpathSync(new URL('../../../node_modules/@bitwarden/cli/build/bw.js', import.meta.url));
  const source = readFileSync(file, 'utf8').replace(/^#![^\n]*\n/, '');
  if (!source.includes('\nbw_main();')) throw new Error('The pinned Bitwarden CLI entrypoint changed');
  const holder = { exports: {} as Record<string, any> };
  const code = source.replace('\nbw_main();', `
    module.exports = { NodeCrypto: bw_NodeCryptoFunctionService, KeyGeneration: bw_KeyGenerationService,
      Encrypt: bw_EncryptServiceImplementation, BaseExport: bw_BaseVaultExportService,
      PasswordImporter: bw_BitwardenPasswordProtectedImporter, CsvImporter: bw_BitwardenCsvImporter,
      Pin: bw_PinService };`);
  new Function('require', 'module', 'exports', '__filename', '__dirname', code)(
    createRequire(file), holder, holder.exports, file, dirname(file));
  return holder.exports;
}
const official = officialCode();
function services(kdf: { kdfType: number; iterations: number; memory?: number; parallelism?: number }) {
  const crypto = new official['NodeCrypto']();
  const generation = new official['KeyGeneration'](crypto);
  const pin = Object.create(official['Pin'].prototype);
  pin.keyGenerationService = generation;
  const encryption = new official['Encrypt'](crypto, { error: () => {} }, false);
  return { exporter: new official['BaseExport'](pin, encryption, crypto, { getKdfConfig: async () => kdf }),
    importer: new official['PasswordImporter'](null, encryption, { t: (key: string) => key }, null, pin, null,
      async () => 'Fixture export password') };
}

const record: VaultItem = { id: 'record', type: 'login', rawType: 1, name: 'Synthetic fixture', nameFailed: false,
  notes: null, notesFailed: false, favorite: false, folderId: null, reprompt: 1,
  createdAt: '2026-01-01', updatedAt: '2026-01-02', deletedAt: null, archivedAt: null, wrappedKey: null,
  login: { ...emptyLogin(), username: 'alice', password: 'secret', uris: [
    { uri: 'https://one.example/path,a', match: 3 }, { uri: 'https://two.example', match: 0 },
  ] }, card: null, identity: null, sshKey: null, secureNote: null, attachments: [],
  customFields: [], passwordHistory: [{ password: 'previous-secret', lastUsedDate: '2025-12-01' }] };

describe('official Bitwarden CLI interoperability', () => {
  it.each([
    { kdfType: 0, iterations: 1000 },
    { kdfType: 1, iterations: 2, memory: 16, parallelism: 2 },
  ])('imports an envelope generated by the official exporter with %j', async kdf => {
    const { exporter } = services(kdf);
    const clear = JSON.stringify({ encrypted: false, folders: [], items: [{ name: 'Official', type: 1,
      login: { username: 'alice', password: 'spaced password ' } }] });
    const envelope = await exporter.buildPasswordExport(clear, 'Fixture export password');
    const result = await parseImport(new TextEncoder().encode(envelope), 'auto', 'Fixture export password');
    expect(result.skipped).toEqual([]);
    expect(result.items[0]?.login?.password).toBe('spaced password ');
  });

  it('imports our encrypted export with the official password-protected importer', { timeout: 30_000 }, async () => {
    const { importer } = services({ kdfType: 0, iterations: 1000 });
    const exported = await createVaultExport({ items: [record], folders: [], format: 'encrypted-json', password: 'Fixture export password' });
    const result = await importer.parse(new TextDecoder().decode(exported.bytes));
    expect(result.success).toBe(true);
    expect(result.ciphers[0]).toMatchObject({ name: 'Synthetic fixture', reprompt: 1,
      login: { username: 'alice', password: 'secret', uris: [{ uri: 'https://one.example/path,a', match: 3 }, { uri: 'https://two.example', match: 0 }] },
      passwordHistory: [{ password: 'previous-secret' }] });
  });

  it('preserves multiple CSV URIs using the official nested CSV representation', async () => {
    const exported = await createVaultExport({ items: [record], folders: [], format: 'csv' });
    const result = await new official['CsvImporter']().parse(new TextDecoder().decode(exported.bytes));
    expect(result.success).toBe(true);
    expect(result.ciphers[0].login.uris.map((uri: { uri: string }) => uri.uri))
      .toEqual(['https://one.example/path,a', 'https://two.example']);
    const imported = await parseImport(exported.bytes);
    expect(imported.items[0]?.login?.uris).toEqual([
      { uri: 'https://one.example/path,a', match: null }, { uri: 'https://two.example', match: null },
    ]);
  });
});
